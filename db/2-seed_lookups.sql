-- ============================================================
-- Recalculate installments from the rate schedule above rather than
-- from a flat 3% formula. The schedule is not linear: 2 months carries
-- 2.80% per month, 6 months carries 3.00%. The formula overcharged
-- every short-duration loan.
--
-- Lookup first; fall back to the formula only for amount/duration
-- combinations the schedule does not cover.
-- ============================================================

create or replace function fn_installment(
  p_amount numeric, p_months int, p_offday text
) returns numeric language sql stable as $$
  select coalesce(
    (select case when p_offday = 'Fri' then r.inst_25d else r.inst_20d end
       from rate_schedule r
      where r.amount = p_amount and r.months = p_months),
    round((p_amount + p_amount * 0.03 * greatest(p_months, 1))
          / nullif(greatest(p_months, 1) * (case when p_offday = 'Fri' then 25 else 20 end), 0))
  );
$$;

create or replace function fn_total_receivable(
  p_amount numeric, p_months int
) returns numeric language sql stable as $$
  select coalesce(
    (select r.total_refund from rate_schedule r
      where r.amount = p_amount and r.months = p_months),
    p_amount + p_amount * 0.03 * greatest(p_months, 1)
  );
$$;

create or replace view v_proposals as
select
  pr.proposal_id,
  pr.old_mcl,
  pr.prospect_date,
  pr.proposed_loan_amount,
  pr.proposed_duration_months,
  vp.last_portfolio      as lst_pfn,
  vp.old_loan_amount,
  m.profile_id,
  m.member_name          as customer_name,
  m.business_name,
  pr.zero_install,
  m.area_code            as area,
  z.name                 as zone,
  c.name                 as category,
  pr.cr_score,
  vp.lfd, vp.led, vp.lsd,
  vp.no_of_portfolios    as mem_pf,
  m.off_day              as offday,
  fn_installment(pr.proposed_loan_amount,
                 coalesce(pr.proposed_duration_months, 1),
                 m.off_day)                    as proposed_installment,
  cro.name               as cro,
  inc.name               as incharge,
  pr.stage
from proposals pr
join members m           on m.profile_id = pr.profile_id
left join v_member_portfolio vp on vp.profile_id = m.profile_id
left join zones z        on z.id = m.zone_id
left join categories c   on c.code = m.category_code
left join employees cro  on cro.emp_id = pr.cro_id
left join employees inc  on inc.emp_id = pr.incharge_id;

create or replace view v_lmc as
with base as (
  select
    l.*,
    pr.prospect_date                       as applied_date,
    pr.proposed_loan_amount                as proposed_amount,
    pr.proposed_duration_months            as prop_dur,
    m.profile_id, m.member_name, m.business_name, m.off_day,
    1                                                                as weekly_off_days_no,
    (case when m.off_day = 'Fri' then 25 else 20 end)                as collection_days_monthly,
    coalesce(l.approved_amount, pr.proposed_loan_amount)             as amt,
    coalesce(l.approved_duration_months, pr.proposed_duration_months, 1) as dur,
    f.fs_score_pct
  from lmc l
  join proposals pr on pr.proposal_id = l.proposal_id
  join members m    on m.profile_id = pr.profile_id
  left join fprc f  on f.proposal_id = l.proposal_id
)
select
  proposal_id, applied_date, approved_date, proposed_amount, prop_dur,
  approved_amount, approved_duration_months,
  pm_check, dir_check, contr_check, ceo_check,
  member_name as customer_name, business_name, profile_id, off_day as offday,
  weekly_off_days_no, collection_days_monthly,
  dur * collection_days_monthly                     as total_no_of_installment,
  fn_total_receivable(amt, dur)                     as total_receivable,
  fn_installment(amt, dur, off_day)                 as proposed_installment_amount,
  coalesce(actual_installment, fn_installment(amt, dur, off_day)) as actual_installment,
  pm_time, approved_time, disbursed_date, start_date, end_date, fs_score_pct as fs_pct
from base;
